"""生成 js/plugins.js。

按固定顺序登记插件；描述与参数默认值从每个插件的注解块里解析。
参数值统一存成字符串（MZ 的存储形式）。
"""

import io
import json
import os
import re

ORDER = [
    # Awaya 的修正插件（MIT License, (C) Awaya_Matana）
    "BlendModeFix",
    "EncounterFix",
    "EquipStatusFix",
    "NameInputFix",
    "OptimizedMovementRoute",
    "PriorityFix",
    "SceneStartFix",
    "SkipControlCharacter",
    "SmoothFont",
    "TouchMovementFix",
    "CenterDamagePopup",
    "EnemyAttackAnimation",
    "FasterBattle",
    "StateOverlayForCharacter",
    "FadeText",
    "OptimizedScrollingText",
    "WindowAvoidsPlayer",
    # 本项目核心系统（必须最后）
    "AE86_Systems",
]

DESC_OVERRIDE = {
    "AE86_Systems": "AE86 核心系统：形态切换、束缚、QTE、色情条",
}


def read_header(name: str) -> str:
    path = os.path.join("js", "plugins", name + ".js")
    if not os.path.exists(path):
        return ""
    with io.open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    # 只取第一个注解块（英文块），到 * / 结束
    start = text.find("/*:")
    if start < 0:
        return ""
    end = text.find("*/", start)
    return text[start:end]


def parse_params(header: str) -> dict:
    """把 @param / @default 解析成 { name: "默认值" }。

    只取每个 @param 之后**第一个** @default——注解块里后面可能还有
    属于其他字段的 @default，覆盖上去会得到错误的值。
    """
    params = {}
    seen = set()
    current = None
    for line in header.splitlines():
        line = line.strip().lstrip("*").strip()
        m = re.match(r"@param\s+(\S+)", line)
        if m:
            current = m.group(1)
            params.setdefault(current, "")
            continue
        m = re.match(r"@default\s*(.*)", line)
        if m and current is not None and current not in seen:
            params[current] = m.group(1).strip()
            seen.add(current)
            continue
    return params


def plugindesc(name: str) -> str:
    if name in DESC_OVERRIDE:
        return DESC_OVERRIDE[name]
    header = read_header(name)
    m = re.search(r"@plugindesc\s+(.+)", header)
    return m.group(1).strip() if m else ""


def main() -> int:
    entries = []
    for name in ORDER:
        if not os.path.exists(os.path.join("js", "plugins", name + ".js")):
            print("MISSING:", name)
            continue
        entries.append(
            {
                "name": name,
                "status": True,
                "description": plugindesc(name),
                "parameters": parse_params(read_header(name)),
            }
        )

    lines = [
        "// Generated by RPG Maker.",
        "// Do not edit this file directly.",
        "var $plugins =",
        "[",
    ]
    for i, e in enumerate(entries):
        comma = "," if i < len(entries) - 1 else ""
        lines.append(json.dumps(e, ensure_ascii=False) + comma)
    lines.append("];")

    with io.open("js/plugins.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    for e in entries:
        if e["parameters"]:
            print(f"{e['name']}: {json.dumps(e['parameters'], ensure_ascii=False)}")
    print("wrote", len(entries), "plugins")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
